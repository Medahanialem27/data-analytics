#Example assets
checking_acount = 500.00
saving_acount = 2000.00
car_value = 8000.00
total_assets = checking_acount + saving_acount + car_value
#Example debts
credit_card_debt = 500.00
car_loan = 3000.00
total_debts = credit_card_debt + car_loan
net_worth = total_assets - total_debts
